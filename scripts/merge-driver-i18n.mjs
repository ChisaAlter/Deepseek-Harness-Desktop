#!/usr/bin/env node
// Custom git merge driver for `*.i18n.yaml` pairing records
// (merge.dshd-translation-pairing). Args: %O %A %B %P — ancestor, ours,
// theirs, and the path being merged. When both owner files merged cleanly
// (no conflict markers on disk) we compose a fresh record from the working
// tree and exit 0. Anything else fails closed and leaves the conflict for
// `scripts/resolve-pairing-conflicts.mjs` / a human.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, basename, resolve } from 'node:path'
import { blobHash, sigHash } from './verify-translation-pairing.mjs'

const [, , ancestor, ours, theirs, mergedPath] = process.argv
const dir = dirname(resolve(mergedPath))
const stem = basename(mergedPath).replace(/\.i18n\.yaml$/, '')
const zh = `${dir}/${stem}.md`
const en = `${dir}/${stem}.en.md`

const dirty = (p) => !existsSync(p) || /^(<{7}|={7}|>{7})/m.test(readFileSync(p, 'utf8'))
if (dirty(zh) || dirty(en)) {
  console.error(`i18n driver: ${stem} owner files not cleanly merged — leaving conflict`)
  process.exit(1)
}
const zhSig = sigHash(readFileSync(zh, 'utf8'))
if (zhSig !== sigHash(readFileSync(en, 'utf8'))) {
  console.error(`i18n driver: ${stem} merged owners have divergent skeletons — leaving conflict`)
  process.exit(1)
}
writeFileSync(
  ours,
  `# pairing confirmation record — regenerated by merge driver dshd-translation-pairing\n` +
    `zh: ${blobHash(readFileSync(zh, 'utf8'))}\n` +
    `en: ${blobHash(readFileSync(en, 'utf8'))}\n` +
    `signature: ${sigHash(readFileSync(zh, 'utf8'))}\n`,
)
console.error(`i18n driver: composed ${mergedPath} from merged owners`)
process.exit(0)
